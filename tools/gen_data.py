"""Generates embedded data files.

  src-tauri/data/oui.tsv.gz  IEEE MA-L/MA-M/MA-S prefixes -> organisation (from oui.csv / mam.csv / oui36.csv)
  ui/world.js                world map (world-atlas countries-110m, public domain) + ISO numeric -> alpha-2

Usage: python tools/gen_data.py <dir with oui.csv>
"""
import csv, gzip, json, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = sys.argv[1]

rows = {}
for name in ('oui.csv', 'mam.csv', 'oui36.csv'):
    p = os.path.join(src, name)
    if not os.path.exists(p):
        continue
    with open(p, encoding='utf-8', errors='replace', newline='') as f:
        for r in csv.DictReader(f):
            org = re.sub(r'\s+', ' ', r['Organization Name']).strip()
            if org:
                rows[r['Assignment'].strip().upper()] = org
os.makedirs(os.path.join(ROOT, 'src-tauri', 'data'), exist_ok=True)
with gzip.open(os.path.join(ROOT, 'src-tauri', 'data', 'oui.tsv.gz'), 'wt', encoding='utf-8', compresslevel=9) as f:
    for k in sorted(rows):
        f.write(f'{k}\t{rows[k]}\n')
print('oui prefixes:', len(rows))

topo = json.load(open(os.path.join(ROOT, 'node_modules', 'world-atlas', 'countries-110m.json'), encoding='utf-8'))
codes = json.load(open(os.path.join(ROOT, 'node_modules', 'i18n-iso-countries', 'codes.json'), encoding='utf-8'))
num2a2 = {c[2]: c[0] for c in codes}   # [alpha2, alpha3, numeric]
with open(os.path.join(ROOT, 'ui', 'world.js'), 'w', encoding='utf-8') as f:
    f.write('// Generated by tools/gen_data.py. Map: world-atlas countries-110m (Natural Earth, public domain).\n')
    f.write('window.WORLD = ' + json.dumps(topo, separators=(',', ':')) + ';\n')
    f.write('window.ISO_NUM = ' + json.dumps(num2a2, separators=(',', ':')) + ';\n')
print('world.js written')
